// Generates js/weather-data.js from the pinned game tables (see tools/lib/gamedata.mjs).
//
//   node tools/build-weather.mjs              download (once, into tools/.cache) and build
//   node tools/build-weather.mjs --csv DIR    read TerritoryType.csv etc. from DIR instead
//   node tools/build-weather.mjs --check      fail if js/weather-data.js is not what this builds
//
// Supported zones come from data/supported-zones.json. Every other city, field zone and
// open-world area that has a weather table is listed by name only, so the page can say it is
// not supported instead of guessing.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { DATASET, ROOT, loadTables, ratePairs } from './lib/gamedata.mjs';

// TerritoryIntendedUse values for places a player stands around in: cities, field zones,
// housing, Eureka, Bozja and Zadnor, Island Sanctuary, Cosmic Exploration and Occult Crescent.
// The game does not name these values; they only choose which names the not-supported list has.
const OPEN_WORLD = new Set([0, 1, 13, 41, 48, 49, 60, 61]);

// Zone keys use the page's own slug function, so URLs and data can never disagree.
export const { slug } = createRequire(import.meta.url)('../js/format.js');

export function buildWeatherData(tables, supported) {
  const place = new Map(tables.PlaceName.map((r) => [r['#'], r.Name]));
  const expansion = new Map(tables.ExVersion.map((r) => [r['#'], r.Name]));
  const weatherName = new Map(tables.Weather.map((r) => [Number(r['#']), r.Name]));
  const rates = new Map(tables.WeatherRate.map((r) => [r['#'], ratePairs(r)]));
  const territory = new Map(tables.TerritoryType.map((r) => [Number(r['#']), r]));

  const zones = [], used = new Set(), seenKeys = new Set();
  for (const entry of supported.zones) {
    const t = territory.get(entry.territory);
    if (!t) throw new Error(`territory ${entry.territory} is not in TerritoryType`);
    const name = place.get(t.PlaceName);
    const pairs = rates.get(t.WeatherRate);
    if (!name) throw new Error(`territory ${entry.territory} has no place name`);
    if (!pairs || t.WeatherRate === '0') throw new Error(`${name} has no weather table`);
    const total = pairs.reduce((s, [, r]) => s + r, 0);
    if (total !== 100) throw new Error(`${name}: weather rates sum to ${total}, not 100`);
    for (const [w] of pairs) {
      if (!weatherName.get(w)) throw new Error(`${name}: weather ${w} has no name`);
      used.add(w);
    }
    const key = slug(name);
    if (seenKeys.has(key)) throw new Error(`duplicate zone key ${key}`);
    seenKeys.add(key);
    const region = entry.region || place.get(t.PlaceNameRegion);
    if (!region || region === '???') throw new Error(`${name} needs a region override`);
    zones.push({
      key, name, territory: entry.territory, region,
      expansion: expansion.get(t.ExVersion), weatherRate: Number(t.WeatherRate), rates: pairs,
    });
  }

  const supportedNames = new Set(zones.map((z) => z.name));
  const unsupported = new Map();
  for (const t of territory.values()) {
    const use = Number(t.TerritoryIntendedUse);
    if (!OPEN_WORLD.has(use) || t.WeatherRate === '0') continue;
    const name = place.get(t.PlaceName);
    if (!name || supportedNames.has(name) || unsupported.has(name)) continue;
    unsupported.set(name, { key: slug(name), name });
  }
  const notSupported = [...unsupported.values()].sort((a, b) => a.name.localeCompare(b.name));

  const weathers = Object.fromEntries([...used].sort((a, b) => a - b).map((w) => [w, weatherName.get(w)]));
  // Expansion names in release order (ExVersion row order), for grouping zones on the page.
  const expansions = [...tables.ExVersion].sort((a, b) => Number(a['#']) - Number(b['#'])).map((r) => r.Name).filter(Boolean);
  return {
    source: { dataset: DATASET.repo, commit: DATASET.commit, patch: DATASET.patch, language: DATASET.language },
    expansions, weathers, zones, unsupported: notSupported,
  };
}

export function renderModule(data) {
  const lines = [
    '// Generated by tools/build-weather.mjs from the game\'s TerritoryType, WeatherRate, Weather,',
    `// PlaceName and ExVersion tables (${data.source.dataset} @ ${data.source.commit.slice(0, 10)}, patch ${data.source.patch}).`,
    '// Do not edit by hand; change data/supported-zones.json and rebuild.',
    '// rates: ordered [weather id, percent] pairs exactly as the game lists them.',
    '(function (root) {',
    '  \'use strict\';',
    '  const data = {',
    `    source: ${JSON.stringify(data.source)},`,
    `    expansions: ${JSON.stringify(data.expansions)},`,
    `    weathers: ${JSON.stringify(data.weathers)},`,
    '    zones: [',
    ...data.zones.map((z) => `      ${JSON.stringify(z)},`),
    '    ],',
    '    // Places that have weather in the game but no forecast here yet.',
    `    unsupported: ${JSON.stringify(data.unsupported)},`,
    '  };',
    '  if (typeof module === \'object\' && module.exports) module.exports = data;',
    '  else root.FFXIV_WEATHER_DATA = data;',
    '})(typeof globalThis !== \'undefined\' ? globalThis : this);',
    '',
  ];
  return lines.join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  const csvDir = args.includes('--csv') ? args[args.indexOf('--csv') + 1] : undefined;
  const supported = JSON.parse(readFileSync(join(ROOT, 'data', 'supported-zones.json'), 'utf8'));
  const text = renderModule(buildWeatherData(await loadTables(csvDir), supported));
  const out = join(ROOT, 'js', 'weather-data.js');
  if (args.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) { console.error('js/weather-data.js is out of date; run node tools/build-weather.mjs'); process.exit(1); }
    console.log('js/weather-data.js matches the pinned game data');
    return;
  }
  writeFileSync(out, text);
  console.log(`wrote js/weather-data.js (patch ${DATASET.patch})`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
